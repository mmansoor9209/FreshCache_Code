#!/usr/bin/env python3
"""
Predicted-class held-out answer audit: sample and task preparation.

Arm A  annotated (collection-time) freshness classes  == the existing held-out audit
Arm B  inference-time PREDICTED freshness classes     == what a deployment sees

Same held-out audit requests, same fresh reference, same test-split stream, same
cache policy / thresholds / risk model / timestamps. The ONLY difference is the
value of each record's `freshness_class`, taken from
outputs/class_predictor/predicted_classes.jsonl (written by
scripts/experiments/calibration_and_measurement/freshness_class_prediction.py) and
swapped exactly as scripts/experiments/main/supplementary_replays.py does it:
    pred_records = [dict(r, freshness_class=p["pred_class"]) ...]

Arm A is gated to reproduce the held-out FreshCache profile in
outputs/validation_split/test_results.json before anything else is built.

Answer reuse: generation is keyed by CONTENT (context hash, question hash).
Greedy decoding is deterministic, so any (question, context) pair already
generated by the held-out audit (outputs/general_audit/answers.jsonl) is reused
verbatim and never regenerated.

CPU only, no web, no GPU. Reads existing artifacts read-only; writes only to
outputs/predicted_class_audit/.
"""
from __future__ import annotations
import sys as _sys; _sys.exit(print(__doc__ or "")) if any(_a in ("-h", "--help") for _a in _sys.argv[1:]) else None   # usage

import os, pathlib; REPO_ROOT = pathlib.Path(os.environ.get("FRESHCACHE_ROOT", ".")).resolve(); import csv, hashlib, json, os, pathlib, sys; import os, pathlib; DATA_ROOT = pathlib.Path(os.environ.get("DATA_DIR") or os.path.join(os.environ.get("FRESHCACHE_ROOT", "."), "data")).resolve(); OUTPUT_ROOT = pathlib.Path(os.environ.get("OUTPUT_DIR") or os.path.join(os.environ.get("FRESHCACHE_ROOT", "."), "outputs")).resolve(); import importlib.util as _ilu; _ds = _ilu.spec_from_file_location("dataset_sizes", os.path.join(os.environ.get("FRESHCACHE_ROOT", "."), "scripts/analysis/dataset_sizes.py")); DS = _ilu.module_from_spec(_ds); _ds.loader.exec_module(DS)
from collections import Counter

os.environ.setdefault("OMP_NUM_THREADS", "4")
HERE = ((OUTPUT_ROOT / "predicted_class_audit"))
ROOT = pathlib.Path(os.environ.get("FRESHCACHE_ROOT", ".")).resolve()
for p in ("freshcache/method", "scripts/data", "", "scripts/baselines/vcache", "scripts/evaluation", "freshcache/simulation", "freshcache/selection_replay_engine"):
    sys.path.insert(0, str(ROOT / p) if p else str(ROOT))
sys.path.insert(0, str(ROOT / "freshcache/selection_replay_engine")); sys.path.insert(0, str(ROOT / "scripts/evaluation/answer_audits"))
os.chdir(ROOT)

import numpy as np                    # noqa: E402
import tiered_cache_model as exp              # noqa: E402
import method_replay as ea               # noqa: E402
import request_schedules as sc                # noqa: E402
import audit_replay as p2                    # noqa: E402  (FreshCache path + ctx_for)

STAGE = (OUTPUT_ROOT / "validation_split")
AUD = ((OUTPUT_ROOT / "general_audit"))
PRED = (OUTPUT_ROOT / "class_predictor/predicted_classes.jsonl")
SCHEDULE, SEED = "zipf_uniform", 42
h, ctx_for = p2.h, p2.ctx_for


def main():
    log = []

    def say(s=""):
        print(s, flush=True); log.append(s)

    say("EXPERIMENT 4 — predicted-class held-out answer audit (predicted_class_audit_sample)")

    queries = exp.load_jsonl(exp.QUERIES_FILE)
    manifest = exp.load_jsonl(exp.MANIFEST_FILE)
    paras = (exp.load_jsonl(exp.PARAPHRASE_FILE)
             if exp.PARAPHRASE_FILE.exists() else [])
    records = exp.build_query_records(queries, manifest, paras)
    exp._QUERY_TO_IDX = {r["query"]: i for i, r in enumerate(records)}
    exp._SIM_MATRIX = np.load(str(exp.SIM_MATRIX_CACHE), mmap_mode="r")
    ea.set_cluster_base(records)

    pred = [json.loads(l) for l in open(PRED, encoding="utf-8") if l.strip()]
    assert len(pred) == len(records) and DS.check("primary_requests", len(records))
    for p, r in zip(pred, records):
        assert p["query_id"] == r["query_id"], "predicted_classes order mismatch"
        assert p["true_class"] == r["freshness_class"], "true-class mismatch"
    pred_records = [dict(r, freshness_class=p["pred_class"])
                    for r, p in zip(records, pred)]
    ch = sum(1 for p in pred if p["pred_class"] != p["true_class"])
    say(f"  predicted classes verified against records: {len(pred):,} rows, "
        f"{ch:,} differ from the annotation ({100*ch/len(pred):.2f}%)")
    say(f"  class mix  annotated {dict(Counter(r['freshness_class'] for r in records))}")
    say(f"  class mix  predicted {dict(Counter(r['freshness_class'] for r in pred_records))}")

    split = json.load(open(STAGE / "split.json", encoding="utf-8"))
    test_c = set(split["test_clusters"])
    sample = json.load(open(AUD / "sample.json", encoding="utf-8"))
    want = [d["query_id"] for d in sample["requests"]]
    assert DS.check("audit_sample_requests", len(want))
    wantset = set(want)
    say(f"  held-out sample: {len(want)} requests (reused verbatim, not resampled)")

    arms = {}
    for tag, recs in (("A_annotated", records), ("B_predicted", pred_records)):
        stream = sc.build_stream(recs, SCHEDULE, SEED)
        assert DS.check("primary_requests", len(stream))
        ts = [(t, r) for t, r in stream
              if (r.get("cluster_id") or r["query_id"]) in test_c]
        assert len(ts) == split["test"]["requests"]
        m, rows = p2.replay(ts, {}, "FreshCache")
        arms[tag] = {"metrics": m, "rows": rows, "stream": ts}
        say(f"  {tag:<12} test replay  saved {m['search_saved_pct']:.4f}%  "
            f"L1 {m['l1_hits']:,}  L2 {m['l2_hits']:,}  L3 {m['l3_hits']:,}  "
            f"searches {m['search_calls']:,}")

    # arm A must reproduce the held-out audit's own FreshCache profile
    pub = json.load(open(AUD / "answer_audit_results.json", encoding="utf-8"))
    tr = json.load(open(STAGE / "test_results.json", encoding="utf-8"))["results"]["FreshCache"]
    a = arms["A_annotated"]["metrics"]
    assert abs(a["search_saved_pct"] - tr["search_saved_pct"]) < 1e-6 \
        and a["l1_hits"] == tr["l1_hits"] and a["l2_hits"] == tr["l2_hits"], \
        f"arm A does not reproduce the recorded test profile: {a}"
    say("  arm A reproduces the recorded held-out FreshCache profile exactly")

    # existing answers, keyed by CONTENT so anything already generated is reused
    have = {}
    for r in (json.loads(l) for l in open(AUD / "answers.jsonl", encoding="utf-8")
              if l.strip()):
        have[(r["key"][1], r["key"][2])] = r["answer"]
    say(f"  existing generated answers available for reuse: {len(have):,} "
        f"(content-keyed)")

    tsmap = {r["query_id"]: t for t, r in arms["A_annotated"]["stream"]}
    out, tasks, comp = [], {}, {tag: Counter() for tag in arms}
    changed = 0
    for d in sample["requests"]:
        qid = d["query_id"]
        rec = {"query_id": qid, "query": d["query"], "gold": d["gold"],
               "fc_annotated": d["fc"], "t": d["t"],
               "fresh_ctx_sha": d["fresh_ctx_sha"],
               "fresh_key": d["fresh_key"]}
        for tag in arms:
            p = arms[tag]["rows"].get(qid)
            assert p is not None, f"{tag}: no row for {qid}"
            tier = p["tier"]
            comp[tag][tier] += 1
            rec[f"{tag}_tier"] = tier
            rec[f"{tag}_similarity"] = p.get("similarity")
            rec[f"{tag}_age"] = p.get("age", 0.0)
            if tier == "L1":
                sctx = ctx_for(tuple(p["stored_answer_ev"]))
                sq = p["stored_answer_query"]
                rec[f"{tag}_mode"] = "stored_answer"
                rec[f"{tag}_gen_query"] = sq
                rec[f"{tag}_ctx_sha"] = h(sctx)
            else:
                pctx = ctx_for(tuple(p["ev"]))
                rec[f"{tag}_mode"] = ("regenerate_l2" if tier == "L2"
                                      else ("realtime_bypass" if tier == "REAL_TIME"
                                            else "regenerate_miss"))
                rec[f"{tag}_gen_query"] = d["query"]
                rec[f"{tag}_ctx_sha"] = h(pctx)
                sctx, sq = pctx, d["query"]
            k = (rec[f"{tag}_ctx_sha"], h(sq))
            rec[f"{tag}_reused_answer"] = k in have
            if k not in have:
                tasks[k] = (sq, sctx)
        rec["decision_changed"] = (
            rec["A_annotated_tier"] != rec["B_predicted_tier"]
            or rec["A_annotated_ctx_sha"] != rec["B_predicted_ctx_sha"])
        changed += rec["decision_changed"]
        rec["class_changed"] = (d["fc"] != next(
            pr["pred_class"] for pr in pred if pr["query_id"] == qid))
        out.append(rec)

    say(f"\n  sample path mix A (annotated): {dict(comp['A_annotated'])}")
    say(f"  sample path mix B (predicted): {dict(comp['B_predicted'])}")
    say(f"  requests whose cache decision changes: {changed} of 400")
    say(f"  answers already available (no regeneration): "
        f"A {sum(1 for r in out if r['A_annotated_reused_answer'])}/{len(out)}, "
        f"B {sum(1 for r in out if r['B_predicted_reused_answer'])}/{len(out)}")
    say(f"  NEW generations required: {len(tasks)}")

    json.dump({"schedule": SCHEDULE, "seed": SEED,
               "n_sample": len(want), "decision_changed": changed,
               "class_changed_in_sample": sum(1 for r in out if r["class_changed"]),
               "path_mix": {k: dict(v) for k, v in comp.items()},
               "arm_metrics": {k: {kk: arms[k]["metrics"][kk] for kk in
                                   ("search_saved_pct", "search_calls", "l1_hits",
                                    "l2_hits", "l3_hits", "fetches")}
                               for k in arms},
               "new_generation_tasks": len(tasks),
               "requests": out},
              open(HERE / "sample_spec.json", "w"), indent=2)
    with open(HERE / "gen_tasks.jsonl", "w", encoding="utf-8") as fh:
        for (cs, qs), (q, c) in tasks.items():
            fh.write(json.dumps({"ctx_sha": cs, "q_sha": qs, "question": q,
                                 "context": c}, ensure_ascii=False) + "\n")
    (HERE / "run.log").write_text("\n".join(log) + "\n", encoding="utf-8")
    say("  wrote sample_spec.json, gen_tasks.jsonl")
    (HERE / "run.log").write_text("\n".join(log) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
